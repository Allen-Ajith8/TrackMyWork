export function getTopicsByLevel(level: DSALevel): DSATopic[] {
  return DSA_TOPICS.filter((t) => t.level === level);
}

export function getProblemsByTopic(topicId: string): LeetCodeProblem[] {
  return LEETCODE_PROBLEMS.filter(
    (p) => p.topicId === topicId || p.topicTags.some((tag) => tag.toLowerCase().replace(/\s+/g, '-') === topicId)
  );
}

export function getProblemById(id: string): LeetCodeProblem | undefined {
  return LEETCODE_PROBLEMS.find((p) => p.id === id);
}

export function getTopicById(id: string): DSATopic | undefined {
  return DSA_TOPICS.find((t) => t.id === id);
}
