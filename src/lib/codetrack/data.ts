export function getProblemsByTopic(topicId: string): LeetCodeProblem[] {
  const normId = (topicId || '').toLowerCase().trim();
  const direct = LEETCODE_PROBLEMS.filter(
    (p) =>
      p.topicId === normId ||
      p.topicTags.some((tag) => {
        const normTag = tag.toLowerCase().replace(/\s+/g, '-');
        return normTag === normId || normTag.includes(normId) || normId.includes(normTag);
      })
  );

  if (direct.length > 0) {
    return direct;
  }

  // Fallback: search problem title or description
  const searchMatched = LEETCODE_PROBLEMS.filter(
    (p) =>
      p.title.toLowerCase().includes(normId.replace(/-/g, ' ')) ||
      p.description.toLowerCase().includes(normId.replace(/-/g, ' '))
  );
  if (searchMatched.length > 0) {
    return searchMatched;
  }

  // Safe fallback to first 6 curriculum problems so 3D folder is NEVER empty
  return LEETCODE_PROBLEMS.slice(0, 6);
}

